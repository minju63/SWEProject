// 긴 표기부터 맞춰야 "소득인정액"이 "소득"에, "주민등록초본"이 "초본"에 잘못 걸리지 않는다
const INDEX = GLOSSARY.flatMap((g) =>
  [g.term, ...g.aliases].map((key) => ({ key: key.replace(/\s+/g, ''), entry: g }))
).sort((a, b) => b.key.length - a.key.length);

export function findTerm(message) {
  const text = message.replace(/\s+/g, '');
  return INDEX.find(({ key }) => text.includes(key))?.entry ?? null;
}

export const findTermByName = (name) => GLOSSARY.find((g) => g.term === name) ?? null;
